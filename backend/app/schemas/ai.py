"""Pydantic schemas for Grok AI recommendations and sustainability reports.

Strictly aligned with docs/api-contracts.md Section 2.6.
"""

from datetime import datetime, timezone
from typing import Any, Dict, List, Literal, Optional
from pydantic import BaseModel, Field


class RecommendationRequest(BaseModel):
    """Request payload for generating grounded AI recommendations."""

    building_id: Optional[str] = Field(None, description="Target building identifier, e.g. LIB")
    scenario_id: Optional[str] = Field(None, description="Linked simulation scenario identifier")
    observation_ids: Optional[List[str]] = Field(default_factory=list, description="Linked observation IDs")
    focus_area: Optional[str] = Field(None, description="Optional inquiry topic or focus area")


class RecommendationResponse(BaseModel):
    """Structured recommendation generated by Grok AI based on verified data."""

    recommendation_id: str = Field(..., description="Unique recommendation ID, e.g. rec-601")
    building_id: Optional[str] = Field(None, description="Target building identifier")
    title: str = Field(..., description="Concise title for the sustainability recommendation")
    summary: str = Field(..., description="Grounded summary of proposed intervention and projected impact")
    priority: Literal["low", "medium", "high"] = Field(..., description="Assigned priority tier")
    priority_score: float = Field(..., ge=0.0, le=10.0, description="Normalized priority score between 0 and 10")
    priority_reasoning: str = Field(..., description="Explanation of factors driving the priority ranking")
    suggested_actions: List[str] = Field(default_factory=list, description="Actionable implementation steps")
    referenced_data: Dict[str, Any] = Field(
        default_factory=dict,
        description="Factual links to scenarios, savings figures, and observation counts",
    )
    provenance_label: str = Field(
        default="ai_generated_explanation",
        description="Data provenance marker identifying AI-generated content",
    )
    created_at: str = Field(
        default_factory=lambda: datetime.now(timezone.utc).isoformat(),
        description="Creation timestamp with UTC timezone",
    )


class ReportRequest(BaseModel):
    """Request payload for compiling a sustainability audit report."""

    scope: str = Field(default="campus_wide", description="Facility scope: campus_wide, LIB, ACADEMIC, or RESIDENCE")
    time_period: str = Field(default="30_days", description="Audit time window: 24_hours, 7_days, or 30_days")
    include_scenarios: Optional[List[str]] = Field(default_factory=list, description="List of simulation scenario IDs to include")
    target_audience: Optional[str] = Field(default="Campus Sustainability Committee", description="Target readership audience")


class ResourceMetricsAudit(BaseModel):
    """Aggregated baseline resource consumption audit."""

    measured_or_simulated_energy_kwh: float = Field(..., description="Cumulative energy consumption in kWh")
    water_litres: float = Field(..., description="Cumulative water volume in litres")
    waste_kg: float = Field(..., description="Cumulative waste weight in kg")


class ObservationsAudit(BaseModel):
    """Summary counts of detected campus anomalies and visual observations."""

    total_detected: int = Field(..., description="Total observations detected")
    confirmed_count: int = Field(..., description="Observations verified by operator")
    resolved_count: int = Field(..., description="Observations resolved after maintenance")
    under_review_count: int = Field(..., description="Observations awaiting review")


class SimulatedInterventionSummary(BaseModel):
    """Summary of deterministic simulation scenario projections."""

    scenario_id: str = Field(..., description="Simulation scenario identifier")
    building_id: str = Field(..., description="Target facility identifier")
    projected_energy_savings_kwh: Optional[float] = Field(None, description="Projected energy reduction in kWh")
    projected_water_savings_litres: Optional[float] = Field(None, description="Projected water volume saved in litres")
    projected_waste_diverted_kg: Optional[float] = Field(None, description="Projected waste diversion in kg")
    projected_cost_savings: Optional[float] = Field(None, description="Projected financial savings in USD")


class StrategicRecommendationItem(BaseModel):
    """Prioritized strategic recommendation action item."""

    priority: Literal["low", "medium", "high"] = Field(..., description="Priority level")
    action: str = Field(..., description="Recommended strategic intervention")
    feasibility: str = Field(..., description="Implementation feasibility tier, e.g. immediate, short_term")


class ReportResponse(BaseModel):
    """Complete sustainability intelligence audit document."""

    report_id: str = Field(..., description="Unique report identifier, e.g. rep-701")
    title: str = Field(..., description="Executive report title")
    scope: str = Field(..., description="Facility scope")
    period: str = Field(..., description="Audit time window")
    executive_summary: str = Field(..., description="Grok AI synthesized executive summary")
    resource_metrics: ResourceMetricsAudit = Field(..., description="Factual resource audit metrics")
    observations_audit: ObservationsAudit = Field(..., description="Visual anomalies and observations audit")
    simulated_interventions_summary: List[SimulatedInterventionSummary] = Field(
        default_factory=list, description="Deterministic simulation projections"
    )
    strategic_recommendations: List[StrategicRecommendationItem] = Field(
        default_factory=list, description="Prioritized strategic recommendations"
    )
    provenance_disclaimer: str = Field(
        ..., description="Data governance and source provenance statement"
    )
    generated_at: str = Field(
        default_factory=lambda: datetime.now(timezone.utc).isoformat(),
        description="Report generation timestamp in UTC",
    )
